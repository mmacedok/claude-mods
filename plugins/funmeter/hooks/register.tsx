const IDLE_FPS = 12
const IDLE_DUR = IDLE_QUADROS[0].length / IDLE_FPS
// Cada um começa 1 s depois do início de um ciclo de respiração (3 s): entra e sai com o corpo na posição neutra.
const IDLE_EM = [49, 55, 61]

// Opacidade com keyTimes precisos (a trilha arredonda para 1% do ciclo, grosso demais para 1/12 s).
function janelas(total: number, inicios: number[], dur: number, dentro: number, fora: number) {
  const vals = [fora]
  const keys = ['0']
  for (const ini of inicios) {
    vals.push(dentro)
    keys.push((ini / total).toFixed(5))
    if (ini + dur < total - 1e-6) {
      vals.push(fora)
      keys.push(((ini + dur) / total).toFixed(5))
    }
  }
  return `<animate attributeName="opacity" calcMode="discrete" values="${vals.join(';')}" keyTimes="${keys.join(';')}" dur="${total}s" repeatCount="indefinite"/>`
}

// Um path por cor em cada quadro (em vez de um rect por bloco): o SVG do idle tem de caber nos 131072 caracteres
// que o engine aceita num Svg, senão a faixa inteira some enquanto o Claude está parado.
function quadroIdle(s: string) {
  const porCor = new Map<string, string>()
  for (const r of s.split(' ')) {
    const [x, y, w, h, c] = r.split(',')
    porCor.set(c, (porCor.get(c) ?? '') + `M${x} ${y}h${w}v${h}h-${w}z`)
  }
  return [...porCor]
    .map(([c, d]) => {
      const [cor, op] = IDLE_CORES[+c].split('|')
      return `<path fill="${cor}"${op ? ` opacity="${op}"` : ''} d="${d}"/>`
    })
    .join('')
}

function idlesQuadros(total: number) {
  return IDLE_QUADROS.map((quadros, k) =>
    quadros
      .map((q, i) => `<g opacity="0">${janelas(total, [IDLE_EM[k] + i / IDLE_FPS], 1 / IDLE_FPS, 1, 0)}${quadroIdle(q)}</g>`)
      .join(''),
  ).join('')
}

